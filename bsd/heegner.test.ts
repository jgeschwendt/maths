import { describe, expect, test } from 'bun:test';
import { type Complex, toCurve } from './analytic.ts';
import { curves } from './ec.ts';
import { compose, distance, heegnerB, reduce, ringClassGroup } from './heegner.ts';
import { machines, models } from './model.ts';

const byText = (x: string, y: string): number => x.localeCompare(y);
const sum = (zs: readonly Complex[], weight: (i: number) => number = () => 1): Complex => [
  zs.reduce((s, z, i) => s + weight(i) * z[0], 0),
  zs.reduce((s, z, i) => s + weight(i) * z[1], 0),
];

describe('the class group of discriminant −175', () => {
  test('six reduced forms, cyclic, generated by [2, −1, 22]', () => {
    const reduced = [];
    for (let a = 1; 3 * a * a <= 175; a += 1) {
      for (let b = 1 - a; b <= a; b += 1) {
        const c = (b * b + 175) / (4 * a);
        // primitive: −175 = 25·(−7), so a common factor could only be 5
        if (
          Number.isSafeInteger(c) &&
          c >= a &&
          !(c === a && b < 0) &&
          [a, b, c].some((n) => n % 5)
        ) {
          reduced.push(`${a},${b},${c}`);
        }
      }
    }
    expect(
      ringClassGroup()
        .map((f) => f.join(','))
        .toSorted(byText),
    ).toEqual(reduced.toSorted(byText));
    expect(reduced).toHaveLength(6);
  });

  test('composition is reduction-invariant and the generator has order 6', () => {
    expect(reduce([7, 21, 22])).toEqual([7, 7, 8]);
    expect(compose([2, 1, 22], [2, -1, 22])).toEqual([1, 1, 44]);
    expect(compose([4, 1, 11], [2, -1, 22])).toEqual([2, 1, 22]);
  });
});

describe('Heegner points of level 1 over K = Q(√−7)', () => {
  test('37 and 389 split in K: B² ≡ −7 (mod 4N) at B = 17 and 185', () => {
    expect([heegnerB(curves['37a1']), heegnerB(curves['389a1'])]).toEqual([17, 185]);
  });

  test('37a1: the machine lands on the generator (0, 0)', () => {
    const { lattice, level1 } = machines['37a1'];
    const [x, y] = toCurve(curves['37a1'], level1.z, lattice);
    expect(Math.hypot(...x, ...y)).toBeLessThan(1e-9);
  });

  test('389a1: the machine lands on a lattice corner, the point at infinity', () => {
    expect(distance(machines['389a1'].level1.z, machines['389a1'].lattice)).toBeLessThan(1e-12);
  });
});

describe('Heegner points of conductor 5', () => {
  for (const k of ['37a1', '389a1'] as const) {
    test(`${k}: the six class-group points are the six Hecke images of τ_K at 5, modulo Λ`, () => {
      const { hecke, lattice, six } = machines[k];
      for (const { z } of six) {
        expect(
          Math.min(...hecke.map((h) => distance([z[0] - h[0], z[1] - h[1]], lattice))),
        ).toBeLessThan(1e-12);
      }
    });

    test(`${k}: the trace relation Σ z_i ≡ a_5·z_K (mod Λ)`, () => {
      const { lattice, level1, six } = machines[k];
      const [s, a5] = [sum(six.map(({ z }) => z)), models[k].a[5]];
      expect(distance([s[0] - a5 * level1.z[0], s[1] - a5 * level1.z[1]], lattice)).toBeLessThan(
        1e-12,
      );
    });
  }

  test('389a1: no point is a corner or a 6-torsion point, and the six sum to a corner', () => {
    const { lattice, six } = machines['389a1'];
    const zs = six.map(({ z }) => z);
    expect(Math.min(...zs.map((z) => distance(z, lattice, 6)))).toBeGreaterThan(0.05);
    expect(distance(sum(zs), lattice)).toBeLessThan(1e-12);
  });

  test("389a1: Kolyvagin's weighted sum Σ i·z_i does not cancel: 0.412983 from Λ, 0.201572 from (1/6)Λ", () => {
    const { lattice, six } = machines['389a1'];
    const d = sum(
      six.map(({ z }) => z),
      (i) => i,
    );
    expect(distance(d, lattice)).toBeCloseTo(0.412983, 6);
    expect(distance(d, lattice, 6)).toBeCloseTo(0.201572, 6);
  });
});
